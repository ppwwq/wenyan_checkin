def enrich_cross_sources():
 aliases={i:DATA[i]['name'].split('・')[0] for i in range(16)}
 aliases[0]='論語'
 for q in questions:
  nums=[int(x) for x in re.findall(r'\[(\d+)\]',q['source']['blockPath'])]
  ci,pi,bi=nums[:3];block=DATA[ci]['pages'][pi]['blocks'][bi]
  context=q['stem']+' '+q['explanation']+' '+DATA[ci]['pages'][pi]['title']
  if block[0] in ['table','polytable']:
   context+=' '+str(block[1][0])+' '+str(block[1][nums[-1]])
  refs={ci}|{i for i,name in aliases.items() if name in context and (i!=12 or any(t in context for t in ['《登樓》','〈登樓〉',"'登樓'",'與登樓比較']))}
  if len(refs)==1:continue
  q['essayIds']=[f'essay-{i+1:02}' for i in sorted(refs)]
  related=[];quotes=[f'《{DATA[ci]["name"]}》\n'+q['quote']]
  for other in sorted(refs-{ci}):
   chosen=quote_for(other,context)
   for op,original in all_quotes(other):
    if clean(original) not in clean(chosen):continue
    ob=next(j for j,b in enumerate(DATA[other]['pages'][op]['blocks']) if b[0]=='annot')
    related.append({**source(other,f'$[{other}].pages[{op}].blocks[{ob}]',original),'essayId':f'essay-{other+1:02}','essayTitle':DATA[other]['name']})
   quotes.append(f'《{DATA[other]["name"]}》\n'+chosen)
  q['quote']='\n\n'.join(quotes)
  q['source']['relatedSources']=related
  q['targetStart']=-1 if not q['target'] else q['quote'].find(q['target'])



def repair_explicit_comparisons():
 pairs={'full-c-01-28-03-80':(4,'先國家之急'), 'full-c-01-28-04-80':(4,'肉袒負荊'), 'full-c-01-28-06-80':(8,'居廟堂之高'), 'full-c-09-14-00-80':(0,'內省不疚')}
