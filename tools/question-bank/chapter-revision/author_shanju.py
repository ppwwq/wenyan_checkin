def judge(n,summary,explanation,truth,reasons,group):
 q=QUESTIONS[n-1];out=[]
 for c in q['choices']:
  a,b=c['text'].split('，')
  chosen=('不正確' not in a,'不正確' not in b)
  parts=[]
  for who,want,actual,why in zip(('甲','乙'),chosen,truth,reasons):
   parts.append(('對'+who+'判斷正確：' if want==actual else '錯在對'+who+'的判斷：')+why)
  out.append('；'.join(parts)+'。')
 edit(n,summary,explanation,out,group=group,note='逐句判甲乙，為四個判斷組合分別指出錯在甲、乙或兩者；保留平行選項。')

