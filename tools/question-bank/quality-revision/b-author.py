def add(id, objective, reason, summary, rows, *, stem=None, quote=None, source=None, supporting=None, g4=None):
    item = byid[id]
    q = item['question']
    choices = []
    audit = []
    for old, row in zip(q['choices'], rows):
        text, explanation, attraction, misreading, follow = row
        choices.append({'id': old['id'], 'text': text, 'explanation': explanation})
        audit.append({'id': old['id'], 'attraction': attraction, 'misreading': misreading,
                      'refutation': explanation, 'followUp': follow, 'evidenceType': 'hypothesis'})
    patch = {'choices': choices, 'explanation': summary, 'summary': summary.split('。')[0]+'。',
             'misconception': '；'.join(r[3] for c,r in zip(q['choices'],rows) if c['id'] != q['answerId']),
             'revisionReason': reason}
    if stem is not None: patch['stem'] = stem
    if quote is not None:
        patch['quote'] = quote
        target=q.get('target','')
        patch['targetStart'] = quote.index(target) if target else 0
    if source is not None: patch['source'] = source
    if supporting is not None: patch['supportingSources'] = supporting
    evidence=[]
    for e in item['evidence']:
        src=e['source']; block=e['block']
        if block[0]=='annot': extract=block[1]
        elif block[0] in ['text','note']: extract=block[1]
        else: extract='；'.join(str(v) for v in block if v!='blue')
        page=src['pdfPage']
        if id=='full-b-08-18-01-1' and src['blockPath']=='$[8].pages[5].blocks[0]': page=159
        evidence.append({'blockPath':src['blockPath'],'pdfPage':page,'quote':extract,'claim':objective})
    if id=='confusable-gui-yueyang-shanju':
        evidence.append({'blockPath':'$[10].pages[2].blocks[3][1][1]','pdfPage':189,'quote':'歸；回來','claim':'乙句的歸是浣女回來；已讀來源區塊並核PDF 189頁文字。'})
    key=next(c for c in choices if c['id']==q['answerId'])
    gates={
        'G1':'已讀所列原文／詞義／解說區塊，沿用用戶指定版本；非官方真題。'+('另核PDF實際159頁《岳陽樓記》第五段，修正舊連結錯頁。' if id=='full-b-08-18-01-1' else ''),
        'G2':f"作者逐項反駁後保留 {q['answerId']}：{key['explanation']}；尚待另一代理交叉審核。",
        'G3':'三錯項分別辨析：'+'；'.join(r[3] for c,r in zip(q['choices'],rows) if c['id']!=q['answerId'])+'。吸引力均為命題假設，未作學生實測。',
        'G4':g4 or ('須依語境完成「'+objective+'」；同層次四項，基礎識別用途不冒稱書面表達能力。'),
        'G5':'保留原 ID、memoryId、選項 ID 和答案 ID；逐項解析已對應新文本。改引文時重算 targetStart；版本由合併器遞增，歷史成績不改。'
    }
    records.append({'id':id,'baseQuestionHash':item['baseQuestionHash'],'decision':'revise','patch':patch,
                    'reason':reason,'objective':objective,'evidence':evidence,'optionAudit':audit,'gates':gates})

