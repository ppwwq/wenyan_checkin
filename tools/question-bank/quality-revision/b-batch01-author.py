def add(id,objective,summary,data,*,stem=None,quote=None,reason='保留原考查目標，重寫相關錯項及各項原文辨析，去掉共用模板解析。'):
    item=byid[id];q=item['question'];rows=[line.split('|') for line in data.strip().splitlines()]
    assert len(rows)==4 and all(len(x)==4 for x in rows),id
    choices=[];audits=[]
    for old,(text,why,attract,follow) in zip(q['choices'],rows):
        choices.append({'id':old['id'],'text':text,'explanation':why})
        audits.append({'id':old['id'],'attraction':attract,'misreading':('正解依據：' if old['id']==q['answerId'] else '待驗證的誤讀：')+why,'refutation':why,'followUp':follow,'evidenceType':'hypothesis'})
    patch={'choices':choices,'explanation':summary,'summary':summary.split('。')[0]+'。','misconception':'；'.join(c['explanation'] for c in choices if c['id']!=q['answerId']),'revisionReason':reason}
    if stem is not None:patch['stem']=stem
    if quote is not None:
        patch['quote']=quote
        patch['targetStart']=quote.index(q['target']) if q.get('target') else 0
    evidence=[]
    for e in item['evidence']:
        src=e['source'];b=e['block']
        txt=b[1] if b[0] in ['annot','text','note'] else '；'.join(str(x) for x in b if x!='blue')
        evidence.append({'blockPath':src['blockPath'],'pdfPage':src['pdfPage'],'quote':txt,'claim':objective})
    key=next(c for c in choices if c['id']==q['answerId'])
    records.append({'id':id,'baseQuestionHash':item['baseQuestionHash'],'decision':'revise','patch':patch,'reason':reason,'objective':objective,'evidence':evidence,'optionAudit':audits,
        'gates':{'G1':'逐題讀本包所附原文／詞注／分析區塊，見evidence。沿用提供版本，不聲稱官方題或教師審定。',
                 'G2':f"作者四項反駁後，{q['answerId']}符合題目：{key['explanation']}",
                 'G3':'三個錯項均列具體文本吸引點、排除理由及補救，屬命題假設而非觀測學生錯因。',
                 'G4':'要完成「'+objective+'」；未以純語氣或唯一長項標出答案。基礎辨義仍按基礎用途保留。',
                 'G5':'沿用原ID、memoryId與答案ID；四項解析與修改後題文相合，高亮重新核對，版本由合併器處理。'}})

