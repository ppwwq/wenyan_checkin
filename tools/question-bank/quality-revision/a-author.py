def resolve(path):
    v=source
    for key,idx in re.findall(r'\.([A-Za-z]+)|\[(\d+)\]',path): v=v[key] if key else v[int(idx)]
    return v
def src(i,path,page,quote):
    s=copy.deepcopy(inputs[i]['question']['source'])
    for k in ['relatedSources','row','excerpt','essayId','questionId','quote','meaning','snippet']: s.pop(k,None)
    s.update(blockPath=path,pdfPage=page,printedPage=page-4,anchor=quote,excerpt=quote,jsonFile='student-content.json')
    assert quote in json.dumps(resolve(path),ensure_ascii=False)
    return s
def add(i,objective,reason,explanation,summary,rows,quote=None,stem=None,extra=None,refs=None,g4=None):
    x=inputs[i]; q=x['question']; patch={'explanation':explanation,'summary':summary,'revisionReason':reason}
    if stem:patch['stem']=stem
    if quote is not None:
        patch['quote']=quote
        target=q.get('target','')
        patch['targetStart']=quote.find(target) if target else 0
        assert not target or patch['targetStart']>=0,(q['id'],target)
    choices=[]; audits=[]
    for old,row in zip(q['choices'],rows):
        text,attraction,misreading,refutation,followup=row.split('|')
        text=text or old['text']
        choices.append({'id':old['id'],'text':text,'explanation':refutation})
        audits.append({'id':old['id'],'attraction':attraction,'misreading':misreading,'refutation':refutation,'followUp':followup,'evidenceType':'hypothesis'})
    patch['choices']=choices
    patch['misconception']='；'.join(a['misreading'] for a in audits if a['id']!=q['answerId'])
    if extra:patch.update(extra)
    evidence=[]; seen=set()
    sources=refs or [e['source'] for e in x['evidence']]
    for s in sources:
        p=s['blockPath']
        if p in seen:continue
        seen.add(p);block=resolve(p)
        txt=s.get('excerpt') or s.get('anchor') or json.dumps(block,ensure_ascii=False)
        # Citation text must literally occur in resolved source; anchors can contain joined table cells.
        flat=json.dumps(block,ensure_ascii=False)
        if txt not in flat:
            txt=block[1] if isinstance(block,list) and len(block)>1 and isinstance(block[1],str) else flat
        evidence.append({'blockPath':p,'pdfPage':s.get('pdfPage'),'quote':txt,'claim':objective})
