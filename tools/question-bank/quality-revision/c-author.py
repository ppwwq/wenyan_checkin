inputs = json.loads((ROOT / 'inputs/c-pilot.json').read_text(encoding='utf-8-sig'))
by_id = {x['question']['id']: x for x in inputs}
bank = json.loads((APP / 'web-study/content/bank.json').read_text(encoding='utf-8-sig'))
student = json.loads((APP / 'web-study/content/sources/student-content.json').read_text(encoding='utf-8-sig'))
sources = {}
for q in bank['questions']:
    s = q.get('source', {})
    if s.get('blockPath') not in sources:
        sources[s.get('blockPath')] = s

records = []

def raw_source(essay, page):
    path = f'$[{essay}].pages[{page}].blocks[0]'
    s = copy.deepcopy(sources[path])
    s.pop('relatedSources', None)
    s['anchor'] = student[essay]['pages'][page]['blocks'][0][1]
    s['excerpt'] = s['anchor']
    s['essayId'] = f'essay-{essay+1:02d}'
    s['essayTitle'] = student[essay]['name']
    return s

def make(ident, objective, stem, options, explanation, summary, reason, shortcut, extra=(), quote=None, assessment=None):
    """options: text, explanation, attraction, misreading, follow-up, one entry per original id."""
    x = by_id[ident]
    q = x['question']
    choices = []
    audit = []
    for old, data in zip(q['choices'], options, strict=True):
        text, refutation, attraction, misreading, followup = data
        choices.append(dict(id=old['id'], text=text, explanation=refutation))
        audit.append(dict(id=old['id'], attraction=attraction, misreading=misreading,
                          refutation=refutation, followUp=followup, evidenceType='hypothesis'))
    patch = dict(stem=stem, choices=choices, explanation=explanation, summary=summary,
                 misconception='；'.join(a['misreading'] for a in audit if a['id'] != q['answerId']),
                 revisionReason=reason)
    if assessment:
        patch['assessmentType'] = assessment
    evidence = []
    for e in x['evidence'][:1]:
        s = e['source']
        text = '；'.join(t for t in e['block'] if isinstance(t, str) and t not in ('text','note','annot','blue'))
        evidence.append(dict(blockPath=s['blockPath'], pdfPage=s['pdfPage'], quote=text, claim=objective))
    ss = [raw_source(a,p) for a,p in extra]
    for s in ss:
        evidence.append(dict(blockPath=s['blockPath'], pdfPage=s['pdfPage'], quote=s['anchor'], claim='補足題幹及逐項排除所需的原文語境'))
    if ss:
        source = copy.deepcopy(q['source'])
        source['relatedSources'] = ss
        patch['source'] = source
    if quote is not None:
        patch.update(quote=quote, target='', targetStart=0)
    rec = dict(id=ident, baseQuestionHash=x['baseQuestionHash'], decision='revise', patch=patch,
               reason=reason, objective=objective, evidence=evidence, optionAudit=audit,
               gates=dict(G1='作者來源核對：'+evidence[0]['quote'],
                          G2='作者逐項反駁：正解 '+q['answerId']+'；'+ '；'.join(c['id']+'：'+c['explanation'] for c in choices),
                          G3='逐項吸引點及排除已記；為命題假設，無學生選項分布。'+ '；'.join(a['id']+'：'+a['attraction'] for a in audit if a['id'] != q['answerId']),
                          G4=shortcut,
                          G5='沿用原 ID、memoryId、答案 ID '+q['answerId']+'；四項解釋已對照新文字。版本由共用合併器遞增；本稿待另一作者交叉審核。'))
    records.append(rec)

