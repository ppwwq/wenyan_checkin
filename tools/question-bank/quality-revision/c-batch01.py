records=[]
def item(n,stem,summary,opts,extra=(),quote=None):
    """Each option is text | evidence-based reason | potential attraction. First is key."""
    x=xs[n];q=x['question'];others=iter(opts[1:]);choices=[];audit=[]
    for c in q['choices']:
        val=opts[0] if c['id']==q['answerId'] else next(others)
        text,why,attraction=val
        choices.append(dict(id=c['id'],text=text,explanation=why))
        audit.append(dict(id=c['id'],attraction=attraction,evidenceType='hypothesis',misreading='正解：'+summary if c['id']==q['answerId'] else why,
            refutation=why,followUp='對照「'+text+'」與解析所指的原句，說明'+('它如何得到支持。' if c['id']==q['answerId'] else '哪一步超出了原文，再改成有據的說法。')))
    explanation=opts[0][1]+' '+summary
    p=dict(stem=stem,choices=choices,explanation=explanation,summary=summary,misconception='；'.join(o[1] for o in opts[1:]),
        revisionReason='按原學習目標重寫同維度四項，解除二人評議的弱斷言／定義答案篇幅提示，附逐項文本反駁。')
    ev=[dict(blockPath=e['source']['blockPath'],pdfPage=e['source']['pdfPage'],quote='；'.join(v for v in e['block'] if isinstance(v,str) and v not in ('text','note','band')),claim=summary) for e in x['evidence'][:1]]
    ss=[]
    for ci,pi in extra:
        bp=f'$[{ci}].pages[{pi}].blocks[0]';s=copy.deepcopy(source_map[bp]);s.pop('relatedSources',None)
        s.update(anchor=student[ci]['pages'][pi]['blocks'][0][1],excerpt=student[ci]['pages'][pi]['blocks'][0][1],essayId=f'essay-{ci+1:02d}',essayTitle=student[ci]['name'])
        assert norm(s['anchor']) in norm(pages[s['pdfPage']-1]),bp
        ss.append(s);ev.append(dict(blockPath=bp,pdfPage=s['pdfPage'],quote=s['anchor'],claim='題引與排除理由的必要原文'))
    if ss:
        src=copy.deepcopy(q['source']);src['relatedSources']=ss;p['source']=src
    if quote is not None:p.update(quote=quote,target='',targetStart=0)
    records.append(dict(id=q['id'],baseQuestionHash=x['baseQuestionHash'],decision='revise',patch=p,reason=p['revisionReason'],objective=summary,
        evidence=ev,optionAudit=audit,gates=dict(G1='對照提供來源：'+ev[0]['quote'],G2='唯一答案 '+q['answerId']+'；'+ '；'.join(c['id']+'：'+c['explanation'] for c in choices),
        G3='三錯項各有局部吸引與排除理由，未當作學生實測：'+'；'.join(o[2] for o in opts[1:]),
        G4='四項回答同一問題，要求辨清：'+summary+'；原文引證排除屬目標操作，非靠荒謬項或答案長度。',
        G5='沿用原四項ID及答案ID；引用新增原文頁面anchor已核。版本由合併器處理，須交叉審後准入。')))

