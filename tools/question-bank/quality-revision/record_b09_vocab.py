def selected_ids():
 queue=read(HERE/'prior-review-work-queue.json')
 excluded=set(read(HERE/'release-manifest.json')['reviewedIds'])
 excluded.update(r['id'] for r in read(HERE/'record-calibration-2026-09-23.json')['records'])
 for p in (HERE/'drafts').glob('*.json'):
  if p==OUT:continue
  excluded.update(r['id'] for r in read(p).get('records',[]))
 return [ident for group in queue['groups']
         if group['status']=='requires-review' and group['essay']=='essay-09'
         and group['ability']=='vocabulary'
         for ident in group['ids'] if ident not in excluded][:20]

def main():
 assert [row[0] for row in DATA]==selected_ids(),'Queue selection changed'
 inputs={r['question']['id']:r for r in read(HERE/'inputs/b-all.json')}
 records=[]
 for ident,reasoning,options in DATA:
  item=inputs[ident];q=item['question'];ids=[c['id'] for c in q['choices']]
  assert ids==['a','b','c','d'] and len(options)==4
  assert q['quote'][q['targetStart']:q['targetStart']+len(q['target'])]==q['target']
  choices=[{'id':cid,'text':option[0],'explanation':option[1]}
           for cid,option in zip(ids,options,strict=True)]
  assert len({c['text'] for c in choices})==4
  evidence=[]
  for source_item in item['evidence']:
   s=source_item['source'];block=source_item['block']
   evidence.append({'blockPath':s['blockPath'],'pdfPage':s['pdfPage'],
                    'quote':'：'.join(str(part) for part in block[:2]),'claim':reasoning})
  audits=[{'id':cid,'attraction':option[2],
           'misreading':('正解依據：' if cid==q['answerId'] else '可能誤讀：')+option[2],
           'refutation':option[1],
           'followUp':'核對「'+q['target']+'」的詞注、主語或前後搭配，分清本句與其他義項。',
           'evidenceType':'hypothesis'}
          for cid,option in zip(ids,options,strict=True)]
  patch={'choices':choices,'explanation':reasoning,'summary':reasoning,
         'misconception':'；'.join(c['explanation'] for c in choices if c['id']!=q['answerId']),
         'revisionReason':'按原句和詞注重寫選項及解析，區分本句義與相近或其他義項。'}
  records.append({'id':ident,'baseQuestionHash':digest(q),'decision':'revise','patch':patch,
    'reason':'按原句和詞注重寫選項及解析，區分本句義與相近或其他義項。',
    'objective':'辨認「'+q['target']+'」在《岳陽樓記》本句的語境義。',
    'evidence':evidence,'optionAudit':audits,
    'gates':{'G1':'PDF第'+str(q['source']['pdfPage'])+'頁原詞注與本句逐項核對；詳見evidence。',
     'G2':'答案'+q['answerId']+'：'+options[ids.index(q['answerId'])][1],
     'G3':'三錯項分別對應不同的誤讀或相鄰詞；吸引點是命題假設，未作學生試測。',
     'G4':'四項同用詞義或句意形式，另待獨立審稿核查唯一答案及猜題線索。',
     'G5':'原ID、memoryId、answerId、target和來源均保留；高亮位置與新解析一致。'}})
 out={'author':'author_record_b09','method':'source-grounded-author-self-check',
      'teacherReview':'not-run','studentTrial':'not-run','records':records}
 if OUT.exists() and read(OUT)!=out:
  history=HERE/'revision-history/record-b09-vocab-before-self-check.json'
  history.parent.mkdir(parents=True,exist_ok=True)
  assert not history.exists() or history.read_bytes()==OUT.read_bytes(),'Self-check backup differs'
  if not history.exists():history.write_bytes(OUT.read_bytes())
 if not OUT.exists() or read(OUT)!=out:
  OUT.write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 print(json.dumps({'draft':str(OUT),'records':len(records),'ids':[r['id'] for r in records]},ensure_ascii=False))

if __name__=='__main__':main()
