import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile,rm} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createApp} from '../backend/server.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const out=new URL('../verification/feedback-dedup-2026-10-15/',import.meta.url);
await mkdir(out,{recursive:true});
const bank=JSON.parse(await readFile(new URL('../content/bank.json',import.meta.url),'utf8'));
const app=createApp({databasePath:':memory:',bootstrapInvite:'local-feedback-qa',adminUsername:'qa-teacher',adminInvite:'local-teacher-qa',staticRoot:fileURLToPath(new URL('../dist/',import.meta.url))});
await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
const origin='http://127.0.0.1:'+app.server.address().port;
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const contexts=[],checks=[],errors=[];
const api=async(route,body,token)=>{
 const response=await fetch(origin+route,{method:body?'POST':'GET',headers:{...(body?{'Content-Type':'application/json'}:{}),...(token?{Authorization:'Bearer '+token}:{})},...(body?{body:JSON.stringify(body)}:{})});
 const value=await response.json();assert.ok(response.ok,route+': '+JSON.stringify(value));return value;
};
const act=(page,action)=>page.locator('[data-action="'+action+'"]:visible').first();
const click=async(page,action)=>{await act(page,action).click();await page.waitForTimeout(100);};
const qid=page=>act(page,'report').getAttribute('data-id');
const show=page=>page.locator('#question-title').waitFor();
const changed=async(page,previous)=>{await page.waitForFunction(id=>document.querySelector('[data-action="report"]')?.dataset.id!==id,previous);await show(page);};
const snapshot=async(page,name)=>{
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'horizontal overflow: '+name);
 await page.screenshot({path:fileURLToPath(new URL(name+'.png',out)),fullPage:true});
};
const login=async page=>{
 page.on('pageerror',error=>errors.push(error.message));await page.goto(origin);
 await page.locator('[name=username]').fill('qa-student');await page.locator('[name=password]').fill('local-password-123');
 await page.locator('#auth-form button[type=submit]').click();
 await page.locator('.home-primary,#training-form').first().waitFor();
};
const nav=async(page,name)=>{if(await act(page,'pause').count())await click(page,'pause');await page.locator('[data-action="nav"][data-page="'+name+'"]:visible').first().click();await page.waitForTimeout(150);};
const sync=async page=>{await nav(page,'account');await click(page,'sync');await page.waitForFunction(()=>document.querySelector('#sync-status')?.textContent.startsWith('已備份'));};
const choose=async(page,right)=>{
 const id=await qid(page),q=bank.questions.find(q=>q.id===id);
 await page.locator('[data-choice="'+(right?q.answerId:q.choices.find(c=>c.id!==q.answerId).id)+'"]').click();
 await page.waitForTimeout(100);await click(page,'submit');await page.locator('.feedback').waitFor();return id;
};
try{
 const student=await api('/api/auth/register',{username:'qa-student',password:'local-password-123',inviteCode:'local-feedback-qa'});
 const teacher=await api('/api/auth/register',{username:'qa-teacher',password:'local-password-123',inviteCode:'local-teacher-qa'});
 const mobile=await browser.newContext({viewport:{width:390,height:844}});contexts.push(mobile);
 const page=await mobile.newPage();await login(page);
 await page.locator('#training-form').waitFor();await page.locator('[name=appendix]').check();await page.locator('#daily-count').fill('2');
 await page.locator('#training-form button[type=submit]').click();await act(page,'daily-start').waitFor();await click(page,'daily-start');await show(page);
 const first=await qid(page);assert.equal(first,'full-d-00-00');
 assert.match(await page.locator('.source-panel').innerText(),/月亮像一隻小船/);
 assert.match(await page.locator('.past-paper-tag').innerText(),/自編題目/);
 assert.equal(await page.locator('[data-action="report"]:visible').count(),1);
 await snapshot(page,'mobile-before-answer');
 await click(page,'report');await page.locator('[name=category]').selectOption({label:'同日重複出題'});
 await page.locator('[name=detail]').fill('本地驗證：未作答時也可以回報。');
 await page.locator('#report-form button[type=submit]').click();await page.locator('#report-form').waitFor({state:'hidden'});
 assert.equal(await page.locator('.feedback').count(),0);checks.push('Report visible before answering; submission preserves unanswered state');
 await choose(page,false);await click(page,'next');await changed(page,first);
 const skipped=await qid(page);await page.locator('[data-choice]').last().click();await page.waitForTimeout(100);
 const draft=await page.locator('.option.selected').getAttribute('data-choice');
 await click(page,'pause');await click(page,'resume');await show(page);
 assert.equal(await qid(page),skipped);assert.equal(await page.locator('.option.selected').getAttribute('data-choice'),draft);
 await page.evaluate(()=>navigator.serviceWorker.ready);await mobile.setOffline(true);
 await page.reload();await act(page,'resume').waitFor();await click(page,'resume');await show(page);
 assert.equal(await qid(page),skipped);assert.equal(await page.locator('.option.selected').getAttribute('data-choice'),draft);
 await click(page,'skip');await changed(page,skipped);const corrected=await choose(page,true);
 assert.notEqual(corrected,first);assert.notEqual(corrected,skipped);
 assert.equal(await page.locator('.correct-explanation[open]').count(),0);
 assert.equal(await page.locator('[data-action="report"]:visible').count(),1);
 await snapshot(page,'mobile-correct-answer');checks.push('Offline reload and resume retain draft; skipped question is replaced; report remains visible after correct answer');
 await click(page,'next');await page.getByRole('button',{name:'返回今日訓練',exact:true}).click();await page.waitForTimeout(100);
 assert.match(await page.locator('.home-details').innerText(),/2／2/);
 assert.equal(await act(page,'retry-today').count(),0);checks.push('Wrong answer is not offered again today; skip does not inflate the daily count');
 await mobile.setOffline(false);await sync(page);
 let synced=await api('/api/sync',{events:[]},student.token);
 assert.equal(synced.events.filter(e=>e.type==='attempt').length,2);
 assert.equal(synced.events.filter(e=>e.type==='browse'&&e.payload.purpose==='practice'&&e.payload.questionId===skipped).length,1);
 const reports=await api('/api/admin/reports',null,teacher.token);
 assert.equal(reports.reports.length,1);assert.equal(reports.reports[0].questionId,first);assert.equal(reports.reports[0].questionVersion,bank.questions.find(q=>q.id===first).version);
 assert.equal(reports.reports[0].answer,undefined);checks.push('Offline events and pre-answer report reach the local server/admin exactly once');
 await nav(page,'home');await click(page,'extra');await act(page,'start').waitFor();await click(page,'start');await show(page);
 const manual=await qid(page);assert.ok(![first,skipped,corrected].includes(manual));
 await sync(page);checks.push('Manual practice excludes all previously displayed daily questions, including skipped work');
 const tablet=await browser.newContext({viewport:{width:768,height:1024}});contexts.push(tablet);
 const other=await tablet.newPage();await login(other);await click(other,'extra');await click(other,'start');await show(other);
 const remote=await qid(other);assert.ok(![first,skipped,corrected,manual].includes(remote));
 await snapshot(other,'tablet-second-device');checks.push('A second browser receives presentation records and excludes questions already seen in other sessions');
 await nav(other,'library');await click(other,'select-all');await other.locator('#sourceKind').selectOption('dse-original');await other.waitForTimeout(100);
 await click(other,'start');await show(other);const originalId=await qid(other),original=bank.questions.find(q=>q.id===originalId);
 assert.equal(original.provenance.kind,'dse-original');assert.match(await other.locator('.past-paper-tag').innerText(),/DSE 原題/);
 assert.equal(await other.locator('#question-title').innerText(),original.stem);
 assert.deepEqual(await other.locator('.option span').allTextContents(),original.choices.map(c=>c.text));
 assert.deepEqual(await other.locator('.option').evaluateAll(items=>items.map(e=>e.dataset.choice)),original.choices.map(c=>c.id));
 await snapshot(other,'tablet-dse-original');checks.push('DSE-only filter displays original wording and fixed option order');
 assert.deepEqual(errors,[]);
 const result={result:'PASS',uiVersion:'2026.10.15.1',bankVersion:bank.version,checks,errors,scope:'Isolated in-memory local accounts; Chromium 390x844 and 768x1024; offline service worker and second-browser sync. No production data accessed.'};
 await writeFile(new URL('result.json',out),JSON.stringify(result,null,2)+'\n');await rm(new URL('failure.json',out),{force:true});console.log(JSON.stringify(result));
}catch(error){
 await writeFile(new URL('failure.json',out),JSON.stringify({error:error.stack,checks,errors},null,2));throw error;
}finally{
 for(const context of contexts)await context.close();await browser.close();await new Promise(resolve=>app.server.close(resolve));app.close();
}
