test('question filters read tags, assessmentType, crossEssay and review types without inventing school tags',()=>{
 const flex=q('flex',['a'],{tags:['school-flex']});
 const loan=q('loan',['a'],{tags:['school-loan']});
 const poly=q('poly',['a'],{assessmentType:'polysemy'});
 const plain=q('plain',['a']);
 const cross=q('cross',['a','b']);
 const pool=[flex,loan,poly,plain,cross];
 assert.deepEqual(available(pool,{essayIds:['a','b'],tags:['school-flex']}).map(x=>x.id),['flex']);
 assert.deepEqual(available(pool,{essayIds:['a','b'],tags:['missing-tag']}),[]);
 assert.deepEqual(available(pool,{essayIds:['a'],assessmentType:'polysemy'}).map(x=>x.id),['poly']);
 assert.deepEqual(available(pool,{essayIds:['a'],assessmentType:['polysemy']}).map(x=>x.id),['poly']);
 assert.deepEqual(available(pool,{essayIds:['a','b'],crossEssay:true}).map(x=>x.id),['cross']);
 assert.deepEqual(available(pool,{essayIds:['a','b'],crossEssay:false}).map(x=>x.id),['flex','loan','poly','plain']);
 assert.deepEqual(available(pool,{essayIds:['a','b'],reviewTypes:['flex','loan']}).map(x=>x.id),['flex','loan']);
 assert.deepEqual(available(pool,{essayIds:['a'],reviewTypes:['context']}).map(x=>x.id),['plain']);
 assert.deepEqual(available(pool,{essayIds:['a'],reviewTypes:['typing']}),[]);
 assert.deepEqual(available(pool,{essayIds:['a','b']}).map(x=>x.id),pool.map(x=>x.id));
 assert.equal(available(bank.questions,{essayIds:essays,reviewTypes:['flex']}).length,0);
 assert.equal(available(bank.questions,{essayIds:essays,reviewTypes:['loan']}).length,0);
 assert.ok(available(bank.questions,{essayIds:essays,reviewTypes:['polysemy']}).length>0);
 assert.ok(available(bank.questions,{essayIds:essays,reviewTypes:['function']}).length>0);
 const context=available(bank.questions,{essayIds:essays,reviewTypes:['context']});
 assert.ok(context.length>0);
 assert.ok(context.every(item=>item.ability==='vocabulary'&&item.assessmentType!=='polysemy'&&!item.tags?.includes('confusable')));
});

test('school vocab batches merge by id and v1 stays ahead of template vocab',()=>{
 const file=JSON.parse(readFileSync(new URL('../content/school-vocab/v1.json',import.meta.url)));
 const manifest=JSON.parse(readFileSync(new URL('../content/school-vocab/manifest.json',import.meta.url)));
 assert.deepEqual(manifest.batches,['v1.json','v1.1.json']);
 const next=JSON.parse(readFileSync(new URL('../content/school-vocab/v1.1.json',import.meta.url)));
 assert.equal(next.items.length,642);
 assert.ok(!next.items.some(item=>item.essayId==='essay-01'||item.essayId==='essay-08'));
 const both=mergeSchoolBatches([file,next]);
 assert.equal(both.length,737);
 const count=section=>both.filter(item=>item.section===section).length;
 assert.deepEqual({gloss:count('gloss'),polysemy:count('polysemy'),flex:count('flex'),loan:count('loan')},{gloss:584,polysemy:92,flex:25,loan:36});
 const red=next.items.find(item=>item.teacherCorrection===true);
 assert.deepEqual(both.find(item=>item.id===red.id).accepted,red.accepted);
 assert.equal(file.items.length,95);
 assert.equal(written.items.length,949);
 const kept=file.items.find(item=>item.id==='school-vocab:essay-08:moshu:004');
 assert.deepEqual(kept.accepted,['到达']);
 assert.equal(kept.teacherCorrection,true);
 const loaded=mergeSchoolBatches([file,{items:[{...kept,accepted:['改掉红笔'],teacherCorrection:false,confidence:'高'}]}]);
 assert.deepEqual(loaded.find(item=>item.id===kept.id).accepted,['到达']);
 const pending=file.items.find(item=>item.confidence==='待核');
 const promoted=mergeSchoolBatches([{items:[pending]},{items:[{...pending,confidence:'高',accepted:pending.accepted.slice(),teacherCorrection:false}]}]);
 assert.equal(promoted.find(item=>item.id===pending.id).confidence,'高');
 assert.deepEqual(loadSchoolVocab({items:[{provenance:{kind:'school-original'},section:'gloss',quote:'子曰',target:'曰',accepted:['說']}]}),[]);
 const sheet=schoolVocabForSheet(mergeSchoolBatches([file]));
 assert.equal(sheet.length,95);
 assert.equal(sheet[0].id,file.items[0].id);
 assert.equal(sheet.filter(item=>item.section==='loan').length,2);
 assert.equal(sheet.filter(item=>item.section==='flex').length,1);
 assert.equal(sheet.filter(item=>item.section==='polysemy').length,10);
 const pendingWritten=sheet.find(item=>item.confidence==='待核');
 assert.equal(writtenResult(pendingWritten,pendingWritten.accepted[0]).correct,null);
 const template=q('full-book-1',['a'],{tags:['full-book-expansion']});
 const authored=q('authored-1',['a'],{tags:['revision-book-authored'],provenance:{kind:'authored'}});
 const official=q('dse-1',['a'],{provenance:{kind:'dse-original'},ability:'meaning'});
 const plain=q('plain',['a'],{ability:'meaning'});
 assert.equal(questionPool(template),'extension');
 assert.equal(questionPool(authored),'basic');
 const drawn=queue([template,authored,official,plain],{essayIds:['a'],count:10,studyPool:'default'},state).map(item=>item.id);
 assert.deepEqual(drawn,['authored-1','dse-1','plain']);
 assert.deepEqual(queue([template,plain],{essayIds:['a'],count:10,studyPool:'extension'},state).map(item=>item.id),['full-book-1']);
 assert.deepEqual(mergeAuthoredBatches([{items:[{id:'authored-new',stem:'題',choices:[{id:'a',text:'甲'}],responseFormat:'single-choice'}]},{items:[{id:'authored-new',stem:'新題',choices:[{id:'a',text:'乙'}],responseFormat:'single-choice',confidence:'待核'}]}],new Set(['authored-1'])).questions.map(item=>item.stem),['題']);
 const expansion=JSON.parse(readFileSync(new URL('../content/authored-expansion/v1.json',import.meta.url)));
 assert.equal(expansion.questions.length,146);
 assert.equal(expansion.daoduHeShuIndex.length,15);
 const bankIds=new Set(bank.questions.map(item=>item.id));
 const merged=mergeAuthoredBatches([expansion],bankIds);
 assert.deepEqual(merged.skipped,['authored-exp-v1-e12-mc02','authored-exp-v1-e14-mc02','authored-exp-v1-e16-mc03','authored-exp-v1-e09-sa01']);
 assert.equal(merged.questions.length,55);
 assert.equal(merged.written.length,87);
 assert.ok(merged.questions.every(item=>item.active===true&&item.status!=='reviewed'&&item.editorial.practiceEnabled===true));
 assert.equal(mergeAuthoredBatches([expansion],new Set()).skipped.length,0);
 const essays=bank.essays.map(item=>item.id);
 assert.equal(available([...bank.questions,...merged.questions],{essayIds:essays,studyPool:'authored'}).filter(item=>String(item.id).startsWith('authored-exp-v1-')).length,55);
 assert.equal(available([...bank.questions,...merged.questions],{essayIds:essays,studyPool:'default'}).filter(item=>String(item.id).startsWith('authored-exp-v1-')).length,55);
});

test('sheet run puts school items first and leaves template written vocab out of the default卷',()=>{
 assert.equal(written.items.length,949);
 assert.equal(written.items.filter(i=>i.kind==='vocabulary').length,659);
 const file=JSON.parse(readFileSync(new URL('../content/school-vocab/v1.json',import.meta.url)));
 const school=mergeSchoolBatches([file]);
 const ordered=sheetQueue(written.items,{},school);
 assert.equal(ordered[0].origin,'school-sheet');
 assert.equal(ordered.filter(item=>item.origin==='school-sheet').length,95);
 const next=JSON.parse(readFileSync(new URL('../content/school-vocab/v1.1.json',import.meta.url)));
 const full=sheetQueue(written.items,{},mergeSchoolBatches([file,next]));
 assert.equal(full.filter(item=>item.origin==='school-sheet').length,737);
 assert.ok(full.slice(0,737).every(item=>item.origin==='school-sheet'));
 assert.equal(full.filter(item=>item.confidence==='待核').length,54+file.items.filter(item=>item.confidence==='待核').length);
 assert.ok(ordered.slice(0,95).every(item=>item.origin==='school-sheet'));
 assert.ok(!ordered.some(item=>String(item.bankQuestionId||'').startsWith('full-')));
 assert.ok(sheetQueue(written.items,{includeTemplate:true}).some(item=>String(item.bankQuestionId||'').startsWith('full-')));
 const loan=sheetQueue(written.items,{section:'loan'},school);
 assert.equal(loan.length,2);
 assert.ok(loan.every(item=>item.section==='loan'));
 const two=ordered.slice(0,2);
 assert.deepEqual(sheetAt(two,0),{index:0,total:2,item:two[0],last:false});
 const html=writtenView(two,{essays:[],questions:[]},[],{itemId:two[0].id,sheet:{ids:two.map(i=>i.id),index:0}});
 assert.match(html,/第 1 \/ 2 題/);
 assert.match(html,/data-action="sheet-next"/);
 assert.doesNotMatch(html,/返回文字練習/);
});

test('home review entry is the type hall, and saved or wrong items stay inside it',()=>{
 const home=homeView({essays:[],questions:[]},project([]));
 assert.match(home,/題型館/);
 assert.match(home,/進入題型館/);
 assert.match(home,/data-page="review"/);
 assert.match(home,/打字測義（看句寫義）/);
 assert.doesNotMatch(home,/home-shortcuts/);
 assert.doesNotMatch(home,/data-page="saved"/);
 const hall=reviewHallView({questions:[],essays:[]},[],[]);
 for(const label of ['語境辨義','打字測義','一詞多義','詞類活用','通假','虛詞','詞義跨篇','句意','主旨','手法'])assert.match(hall,new RegExp(label));
 assert.match(hall,/review-sub/);
 assert.match(hall,/錯題/);
 assert.match(hall,/data-page="saved"/);
 assert.match(hall,/data-page="weakness"/);
 assert.match(hall,/data-page="quick"/);
 const library=libraryView({questions:[],essays:[{id:'e',title:'篇'}]},project([]),{essayIds:['e'],count:10,scope:'all',ability:'',studyPool:'basic',appendix:false,reviewTypes:['flex']});
 assert.match(library,/data-review-type="flex"/);
 assert.match(library,/打字卷/);
 const typing=libraryView({questions:[],essays:[{id:'e',title:'篇'}]},project([]),{essayIds:['e'],count:10,scope:'all',ability:'',studyPool:'basic',appendix:false,reviewTypes:['typing']});
 assert.match(typing,/開打字測義卷/);
 assert.match(typing,/不在選擇題/);
});
